from django.conf import settings
from django.db import models


class Lab(models.Model):
    """
    A pedagogical cybersecurity lab.
    Can be created manually by a trainer, or requested by a student
    and (later) generated by the AI Lab Generator.
    """

    class Difficulty(models.TextChoices):
        EASY = 'EASY', 'Facile'
        MEDIUM = 'MEDIUM', 'Moyen'
        HARD = 'HARD', 'Difficile'

    class Category(models.TextChoices):
        WEB = 'WEB', 'Web Security'
        CRYPTO = 'CRYPTO', 'Cryptographie'
        FORENSICS = 'FORENSICS', 'Forensics'
        NETWORKING = 'NETWORKING', 'Networking'
        REVERSE = 'REVERSE', 'Reverse Engineering'
        OSINT = 'OSINT', 'OSINT'

    class Status(models.TextChoices):
        DRAFT = 'DRAFT', 'Brouillon'
        REVIEW = 'REVIEW', 'En attente de validation'
        PUBLISHED = 'PUBLISHED', 'Publié'
        ARCHIVED = 'ARCHIVED', 'Archivé'

    class Source(models.TextChoices):
        MANUAL = 'MANUAL', 'Créé manuellement'
        AI_GENERATED = 'AI_GENERATED', 'Généré par IA'

    # --- Content ---
    title = models.CharField(max_length=255)
    description = models.TextField()
    difficulty = models.CharField(
        max_length=10, choices=Difficulty.choices, default=Difficulty.EASY,
    )
    category = models.CharField(
        max_length=20, choices=Category.choices, default=Category.WEB,
    )
    objectives = models.TextField(
        blank=True, help_text="Objectifs pédagogiques, une ligne par objectif."
    )
    scenario = models.TextField(
        blank=True, help_text="Contexte / histoire du laboratoire."
    )
    hints = models.TextField(blank=True)
    flag = models.CharField(
        max_length=255, blank=True,
        help_text="Réponse attendue (le flag).",
    )
    solution = models.TextField(
        blank=True, help_text="Explication de la solution (visible après réussite)."
    )

    # --- Workflow ---
    status = models.CharField(
        max_length=10, choices=Status.choices, default=Status.DRAFT,
    )
    source = models.CharField(
        max_length=15, choices=Source.choices, default=Source.MANUAL,
    )
    ai_prompt = models.TextField(
        blank=True, help_text="Prompt utilisé si le lab a été généré par IA.",
    )

    # --- Ownership ---
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name='labs_created',
    )
    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name='labs_reviewed',
    )

    # --- Timestamps ---
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    published_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.get_status_display()}] {self.title}"


class LabSession(models.Model):
    """
    One attempt of one student on one lab.
    """

    class Status(models.TextChoices):
        RUNNING = 'RUNNING', 'En cours'
        COMPLETED = 'COMPLETED', 'Terminé'
        ABANDONED = 'ABANDONED', 'Abandonné'

    lab = models.ForeignKey(
        Lab, on_delete=models.CASCADE, related_name='sessions',
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='lab_sessions',
    )
    status = models.CharField(
        max_length=12, choices=Status.choices, default=Status.RUNNING,
    )
    solved = models.BooleanField(default=False)
    submitted_flag = models.CharField(max_length=255, blank=True)
    score = models.IntegerField(default=0)

    started_at = models.DateTimeField(auto_now_add=True)
    finished_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-started_at']

    def __str__(self):
        return f"{self.user} — {self.lab.title} ({self.get_status_display()})"


class LabReview(models.Model):
    """
    Audit trail of every trainer decision on a lab.
    """

    class Decision(models.TextChoices):
        APPROVED = 'APPROVED', 'Approuvé'
        REJECTED = 'REJECTED', 'Rejeté'

    lab = models.ForeignKey(
        Lab, on_delete=models.CASCADE, related_name='reviews',
    )
    reviewer = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='lab_reviews',
    )
    decision = models.CharField(max_length=10, choices=Decision.choices)
    comment = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.lab.title} — {self.get_decision_display()} par {self.reviewer}"