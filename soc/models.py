from django.conf import settings
from django.db import models


class SecurityEvent(models.Model):
    """
    Raw events generated by the labs (e.g., login attempts, network traffic).
    """
    class Severity(models.TextChoices):
        LOW = 'LOW', 'Basse'
        MEDIUM = 'MEDIUM', 'Moyenne'
        HIGH = 'HIGH', 'Haute'
        CRITICAL = 'CRITICAL', 'Critique'

    event_type = models.CharField(max_length=100, help_text="ex: ssh_login_failed")
    source_ip = models.GenericIPAddressField()
    target_asset = models.CharField(max_length=255, help_text="ex: WebServer01")
    payload = models.TextField(blank=True, help_text="Les détails bruts de l'événement")
    severity = models.CharField(max_length=10, choices=Severity.choices, default=Severity.LOW)
    timestamp = models.DateTimeField(auto_now_add=True)
    
    class Meta:
        ordering = ['-timestamp']

    def __str__(self):
        return f"[{self.severity}] {self.event_type} from {self.source_ip}"


class Alert(models.Model):
    """
    Generated when a rule matches one or more events.
    """
    class Status(models.TextChoices):
        NEW = 'NEW', 'Nouveau'
        ACKNOWLEDGED = 'ACKNOWLEDGED', 'Pris en compte'
        IGNORED = 'IGNORED', 'Ignoré'
        INCIDENT = 'INCIDENT', 'Converti en incident'

    title = models.CharField(max_length=255)
    description = models.TextField()
    severity = models.CharField(max_length=10, choices=SecurityEvent.Severity.choices)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.NEW)
    
    # Link to the events that triggered this alert
    events = models.ManyToManyField(SecurityEvent, related_name='alerts')
    
    created_at = models.DateTimeField(auto_now_add=True)
    
    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.status}] {self.title}"


class Incident(models.Model):
    """
    Created from an Alert when an analyst decides it requires investigation.
    """
    class Status(models.TextChoices):
        OPEN = 'OPEN', 'Ouvert'
        INVESTIGATING = 'INVESTIGATING', 'En cours d\'investigation'
        RESOLVED = 'RESOLVED', 'Résolu'
        CLOSED = 'CLOSED', 'Fermé'

    title = models.CharField(max_length=255)
    description = models.TextField()
    severity = models.CharField(max_length=10, choices=SecurityEvent.Severity.choices)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.OPEN)
    
    # Link to the alert that created this incident
    alert = models.OneToOneField(Alert, on_delete=models.SET_NULL, null=True, blank=True, related_name='incident')
    
    # Link to the analyst handling the incident
    assigned_to = models.ForeignKey(
        settings.AUTH_USER_MODEL, 
        on_delete=models.SET_NULL, 
        null=True, blank=True, 
        related_name='assigned_incidents'
    )
    
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    
    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.status}] {self.title}"


class IncidentEvidence(models.Model):
    """Proof/evidence attached to an incident (logs, IPs, file hashes)."""
    incident = models.ForeignKey(Incident, on_delete=models.CASCADE, related_name='evidences')
    description = models.TextField(help_text="Description de la preuve (ex: Log SSH)")
    file_hash = models.CharField(max_length=255, blank=True, help_text="SHA256 du fichier si applicable")
    added_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']


class IncidentHistory(models.Model):
    """Audit trail for every action taken on an incident."""
    incident = models.ForeignKey(Incident, on_delete=models.CASCADE, related_name='history')
    action = models.CharField(max_length=255, help_text="ex: Changement de statut, Preuve ajoutée")
    details = models.TextField(blank=True)
    performed_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True)
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-timestamp']

    